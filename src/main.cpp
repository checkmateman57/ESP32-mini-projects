#include <Arduino.h>

const int A = 13;
const int B = 12;
const int C = 14;
const int D = 27;
const int E = 26;
const int F = 25;
const int G = 33;
const int H = 32;
const int I = 21;
const int J = 34;

void setup() {
  pinMode(A, OUTPUT);
  pinMode(B, OUTPUT);
  pinMode(C, OUTPUT);
  pinMode(D, OUTPUT);
  pinMode(E, OUTPUT);
  pinMode(F, OUTPUT);
  pinMode(G, OUTPUT);
  pinMode(H, OUTPUT);
  pinMode(I, OUTPUT);
  pinMode(J, OUTPUT);
}

void  loop() {
  digitalWrite(A, HIGH);
  delay(100);
  digitalWrite(B, HIGH);
  delay(100);
  digitalWrite(C, HIGH);
  delay(100);
  digitalWrite(D, HIGH);
  delay(100);
  digitalWrite(E, HIGH);
  delay(100);
  digitalWrite(F, HIGH);
  delay(100);
  digitalWrite(G, HIGH);
  delay(100);
  digitalWrite(H, HIGH);
  delay(100);
  digitalWrite(I, HIGH);
  delay(100);
  digitalWrite(J, HIGH);
  delay(100);
  digitalWrite(A, LOW);
  delay(100);
  digitalWrite(B, LOW);
  delay(100);
  digitalWrite(C, LOW);
  delay(100);
  digitalWrite(D, LOW);
  delay(100);
  digitalWrite(E, LOW);
  delay(100);
  digitalWrite(F, LOW);
  delay(100);
  digitalWrite(G, LOW);
  delay(100);
  digitalWrite(H, LOW);
  delay(100);
  digitalWrite(I, LOW);
  delay(100);
  digitalWrite(J, LOW);
  delay(100);


}